//! Deterministic TypeScript declarations from the same schemas used at runtime.
use anyhow::{Context, Result, ensure};
use serde_json::{Value, json};
use std::{collections::BTreeMap, fs, path::Path};

const HEADER: &str = "// Generated by cargo run -p job-harness-dev -- contracts. Do not edit; JSON schemas govern runtime validation.\nexport type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };\nexport interface Envelope<T = JsonValue> { schema_version: 2; ok: boolean; data: T | null; error: { code: string; message: string; retryable: boolean; recovery: string } | null; next: Array<{ tool: string; arguments: JsonValue; reason: string }> }\nexport interface ToolArguments {\n";
fn literal(value: &Value) -> String {
    match value {
        Value::String(text) => {
            let quoted = serde_json::to_string(text).expect("string serialization");
            let mut out = String::new();
            for ch in quoted.chars() {
                if ch.is_ascii() {
                    out.push(ch);
                } else {
                    for unit in ch.encode_utf16(&mut [0; 2]) {
                        out.push_str(&format!("\\u{unit:04x}"));
                    }
                }
            }
            out
        }
        Value::Array(values) => format!(
            "[{}]",
            values.iter().map(literal).collect::<Vec<_>>().join(", ")
        ),
        Value::Object(fields) => format!(
            "{{{}}}",
            fields
                .iter()
                .map(|(key, value)| format!("{}: {}", literal(&json!(key)), literal(value)))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        _ => String::from_utf8(job_harness_domain::canonical::encoded(value))
            .expect("JSON UTF-8")
            .trim_end_matches('\n')
            .to_owned(),
    }
}
fn type_of(schema: &Value) -> String {
    if let Some(values) = schema["enum"].as_array() {
        return values.iter().map(literal).collect::<Vec<_>>().join(" | ");
    }
    for kind in ["oneOf", "anyOf"] {
        if let Some(branches) = schema[kind].as_array() {
            return branches
                .iter()
                .map(|branch| format!("({})", type_of(branch)))
                .collect::<Vec<_>>()
                .join(" | ");
        }
    }
    if let Some(kinds) = schema["type"].as_array() {
        return kinds
            .iter()
            .map(|kind| {
                let mut branch = schema.clone();
                branch["type"] = kind.clone();
                type_of(&branch)
            })
            .collect::<Vec<_>>()
            .join(" | ");
    }
    match schema["type"].as_str() {
        Some("number" | "integer") => "number".into(),
        Some(kind @ ("string" | "boolean" | "null")) => kind.into(),
        Some("array") => format!("Array<{}>", type_of(&schema["items"])),
        Some("object") => {
            let Some(fields) = schema["properties"]
                .as_object()
                .filter(|fields| !fields.is_empty())
            else {
                return "Record<string, JsonValue>".into();
            };
            let required = schema["required"].as_array().cloned().unwrap_or_default();
            format!(
                "{{ {} }}",
                fields
                    .iter()
                    .map(|(key, value)| format!(
                        "{}{}: {};",
                        literal(&json!(key)),
                        if required.contains(&json!(key)) {
                            ""
                        } else {
                            "?"
                        },
                        type_of(value)
                    ))
                    .collect::<Vec<_>>()
                    .join(" ")
            )
        }
        _ => "JsonValue".into(),
    }
}
fn render(specs: &Value) -> Result<String> {
    let specs = specs
        .as_object()
        .context("Tool catalog must be an object")?;
    let sorted: BTreeMap<_, _> = specs.iter().collect();
    let mut result = HEADER.to_owned();
    result.push_str(
        &sorted
            .into_iter()
            .map(|(name, spec)| {
                format!(
                    "  {}: {};",
                    literal(&json!(name)),
                    type_of(&spec["inputSchema"])
                )
            })
            .collect::<Vec<_>>()
            .join("\n"),
    );
    result.push_str("\n}\nexport type ToolName = keyof ToolArguments;\n");
    Ok(result)
}
pub fn generate(root: &Path, check: bool) -> Result<Value> {
    let specs =
        serde_json::from_slice::<Value>(&fs::read(root.join("resources/schemas/tools.json"))?)?;
    let result = render(&specs)?;
    let destination = root.join("gui/contracts.d.ts");
    if check {
        ensure!(
            fs::read_to_string(&destination).ok().as_deref() == Some(&result),
            "Regenerate declarations: cargo run -p job-harness-dev -- contracts"
        );
    } else {
        fs::write(destination, &result)?;
    }
    Ok(
        json!({"ok":true,"task":"contracts","tools":specs.as_object().map_or(0, serde_json::Map::len),"checked":check}),
    )
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn schema_unions_optionality_and_unicode_match_the_historical_generator() {
        let schema = json!({"type":"object","properties":{"required":{"enum":["£","😀"]},"optional":{"anyOf":[{"type":"array","items":{"type":"integer"}},{"type":"null"}]}},"required":["required"]});
        assert_eq!(
            type_of(&schema),
            "{ \"required\": \"\\u00a3\" | \"\\ud83d\\ude00\"; \"optional\"?: (Array<number>) | (null); }"
        );
        assert_eq!(literal(&json!({"a":[true,1]})), "{\"a\": [true, 1]}");
    }
    #[test]
    fn output_is_sorted_by_tool_name_and_preserves_field_order() {
        let result = render(&json!({"z":{"inputSchema":{"type":"object"}},"a":{"inputSchema":{"type":"object","properties":{"second":{"type":"boolean"},"first":{"type":"string"}}}}})).unwrap();
        assert!(result.find("\"a\"").unwrap() < result.find("\"z\"").unwrap());
        assert!(result.contains("\"second\"?: boolean; \"first\"?: string;"));
    }
}
