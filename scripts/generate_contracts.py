#!/usr/bin/env python3
"""Generate portable TypeScript input contracts from the authoritative tool schemas."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
def type_of(schema):
    if "enum" in schema: return " | ".join(json.dumps(v) for v in schema["enum"])
    for union in ["oneOf","anyOf"]:
        if union in schema: return " | ".join("("+type_of(v)+")" for v in schema[union])
    kind = schema.get("type")
    if isinstance(kind,list): return " | ".join(type_of({**schema,"type":k}) for k in kind)
    if kind in ["number","integer"]: return "number"
    if kind in ["string","boolean","null"]: return kind
    if kind == "array": return "Array<"+type_of(schema.get("items",{}))+">"
    if kind == "object":
        fields=schema.get("properties",{});required=schema.get("required",[])
        if not fields: return "Record<string, JsonValue>"
        return "{ "+" ".join(json.dumps(k)+("" if k in required else "?")+": "+type_of(v)+";" for k,v in fields.items())+" }"
    return "JsonValue"
def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument("--check",action="store_true");args=parser.parse_args()
    specs=json.loads((ROOT/"resources/schemas/tools.json").read_text(encoding="utf-8"))
    output="// Generated by scripts/generate_contracts.py. Do not edit; JSON schemas govern runtime validation.\nexport type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };\nexport interface Envelope<T = JsonValue> { schema_version: 2; ok: boolean; data: T | null; error: { code: string; message: string; retryable: boolean; recovery: string } | null; next: Array<{ tool: string; arguments: JsonValue; reason: string }> }\nexport interface ToolArguments {\n"
    output += "\n".join("  "+json.dumps(k)+": "+type_of(v["inputSchema"])+";" for k,v in sorted(specs.items()))
    output += "\n}\nexport type ToolName = keyof ToolArguments;\n"
    destination=ROOT/"gui/contracts.d.ts"
    if args.check:
        if not destination.exists() or destination.read_text(encoding="utf-8")!=output: raise SystemExit("Regenerate TypeScript contracts: python3 scripts/generate_contracts.py")
    else: destination.write_text(output, encoding="utf-8")
if __name__=="__main__":main()
